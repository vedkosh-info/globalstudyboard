export interface College {
  id: string;
  slug: string;
  nameEn: string;
  type: CollegeType;
  /** Primary home region (where the institution physically sits). */
  region: RegionSlug;
  /**
   * Extra regions this unit is ALSO relevant to, beyond `region`. Universities
   * usually sit in one place, so this is rarely needed; when present, the unit
   * also surfaces under every listed region. See `resolveDisplayRegions()`.
   */
  regions?: RegionSlug[];
  country: CollegeCountry;
  city: string;
  state?: string;
  established: number;
  /**
   * QS, THE, or NIRF only. A band (for example 801–1000) is not a number and
   * stays out of this field. `qsYear` / `theYear` and the tied flags are set
   * only when that edition was read on the publisher’s own page.
   */
  ranking?: {
    nirf?: number;
    qs?: number;
    the?: number;
    qsYear?: number;
    theYear?: number;
    qsTied?: boolean;
    theTied?: boolean;
  };
  admissionExams: string[];
  applicationPlatform?: string;
  programLevels: ProgramLevel[];
  englishTaught: boolean;
  websiteUrl?: string;
  descriptionEn: string;
  courses: string[];
  /**
   * Day the facts in this profile were read on the university’s own pages.
   * Profiles without it keep the site review date. Never a fee, a rank, or a
   * deadline that was not on those pages.
   */
  lastVerified?: string;
}

