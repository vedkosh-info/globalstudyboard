/** API failures are translated; database diagnostics and user data are never shown or logged. */
export function scholarshipError(message = ''): string {
  if (message.includes('scholarship_entries_guide_cycle_idx')) return SCHOLARSHIP_UI.duplicateCycle;
  if (message.includes('_stale')) return SCHOLARSHIP_UI.stale;
  if (message.includes('_not_found')) return SCHOLARSHIP_UI.gone;
  if (message.includes('_cap')) return SCHOLARSHIP_UI.cap;
  if (message.includes('scholarship_application_invalid')) return SCHOLARSHIP_UI.applicationInvalid;
  if (message.includes('scholarship_budget_already_added')) return SCHOLARSHIP_UI.budgetAlready;
  if (message.includes('scholarship_budget_')) return SCHOLARSHIP_UI.budgetInvalid;
  return SCHOLARSHIP_UI.failed;
}
